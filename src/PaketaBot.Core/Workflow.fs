namespace PaketaBot

open System

type IGitHubGateway =
    abstract GetRepository: owner: string * name: string -> Async<Repository>
    abstract TryGetPublication: Repository -> Async<Publication option>
    abstract GetBranchHead: repository: Repository * branch: string -> Async<string option>
    abstract CreateCommit: update: PublishUpdate * parentShas: string list -> Async<string>
    abstract CreateBranch: repository: Repository * branch: string * commitSha: string -> Async<unit>
    abstract FastForwardBranch: repository: Repository * branch: string * commitSha: string -> Async<unit>
    abstract CreatePullRequest: update: PublishUpdate -> Async<int>
    abstract UpdatePullRequest: update: PublishUpdate * pullRequestNumber: int -> Async<unit>

type IPaketResolver =
    abstract Resolve: unit -> Async<ResolutionResult>

module PullRequestBody =
    [<Literal>]
    let private MaximumRows = 50

    [<Literal>]
    let private MaximumCellCharacters = 120

    let private cell (value: string) =
        let bounded =
            if value.Length > MaximumCellCharacters then
                value.Substring(0, MaximumCellCharacters) + "…"
            else
                value

        bounded.Replace("|", "¦").Replace("`", "ˋ").Replace("\r", " ").Replace("\n", " ")

    let private truncationNote actualCount =
        if actualCount > MaximumRows then
            $"\n\nThe table is limited to the first {MaximumRows} of {actualCount} detected changes."
        else
            ""

    /// Describe the observable lock-file change without inventing package upgrades.
    ///
    /// decision: reports dependency requirements separately because they can change without upgrading resolved packages
    /// invariant: an empty resolved-version diff never claims that package versions were updated
    /// decision: bounds and neutralizes lock-derived table cells because package metadata is untrusted Markdown input
    /// invariant: each table contains at most 50 rows and each input cell is truncated to 120 characters before rendering
    let render (changes: VersionChange list) (requirementChanges: RequirementChange list) =
        match changes, requirementChanges with
        | [], [] ->
            $"""{PullRequests.Marker}
Paket refreshed `paket.lock` without changing resolved package versions.

No resolved version or dependency-requirement change could be summarized from the lock file.

Generated by PaketaBot. Repository CI remains responsible for validation.
"""
        | [], requirementChanges ->
            let rows =
                requirementChanges
                |> List.truncate MaximumRows
                |> List.map (fun change ->
                    $"| `{cell change.Name}` | `{cell change.RequiredBy}` | `{cell change.Previous}` | `{cell change.Current}` |")
                |> String.concat "\n"

            let note = truncationNote requirementChanges.Length

            $"""{PullRequests.Marker}
Paket refreshed dependency requirements recorded in `paket.lock` without changing resolved package versions.

| Package | Required by | From | To |
|---|---|---:|---:|
{rows}
{note}

Generated by PaketaBot. Repository CI remains responsible for validation.
"""
        | changes, requirementChanges ->
            let rows =
                changes
                |> List.truncate MaximumRows
                |> List.map (fun change ->
                    $"| `{cell change.Name}` | `{cell change.Previous}` | `{cell change.Current}` |")
                |> String.concat "\n"

            let changeNote = truncationNote changes.Length

            let requirements =
                match requirementChanges with
                | [] -> ""
                | requirementChanges ->
                    let requirementRows =
                        requirementChanges
                        |> List.truncate MaximumRows
                        |> List.map (fun change ->
                            $"| `{cell change.Name}` | `{cell change.RequiredBy}` | `{cell change.Previous}` | `{cell change.Current}` |")
                        |> String.concat "\n"

                    let note = truncationNote requirementChanges.Length

                    $"""

Paket also refreshed dependency requirements recorded in `paket.lock`.

| Package | Required by | From | To |
|---|---|---:|---:|
{requirementRows}
{note}
"""

            $"""{PullRequests.Marker}
PaketaBot updated the versions allowed by `paket.dependencies`.

| Package | From | To |
|---|---:|---:|
{rows}
{changeNote}
{requirements}

Generated by PaketaBot. Repository CI remains responsible for validation.
"""

type ResolveService(resolver: IPaketResolver) =
    /// Resolve one dependency update without publisher credentials.
    ///
    /// invariant: resolver exceptions become typed failures that can cross the Actions artifact boundary
    member _.Run() =
        async {
            try
                return! resolver.Resolve()
            with _ ->
                return {
                    Status = Failed
                    LockFile = None
                    Changes = []
                    RequirementChanges = []
                    Messages = [ "Paket dependency resolution failed before producing a safe result." ]
                }
        }

type PublishService(github: IGitHubGateway) =
    let publication branch pullRequestNumber headSha = {
        Branch = branch
        PullRequestNumber = pullRequestNumber
        HeadSha = headSha
        IsOpen = true
    }

    let createPullRequestAfterBranchMutation update commitSha =
        async {
            let! result = github.CreatePullRequest update |> Async.Catch

            return
                match result with
                | Choice1Of2 pullRequestNumber -> Ok(publication update.Branch pullRequestNumber commitSha)
                | Choice2Of2 _ ->
                    Error(
                        $"GitHub did not confirm a pull request after updating {update.Branch}. "
                        + "Rerun PaketaBot first; if no owned pull request exists, follow PaketaBot's recovery procedure."
                    )
        }

    /// Publish one typed dependency resolution from the credential-free job.
    ///
    /// decision: uses the marked pull request as durable publication state because the Action has no database
    /// invariant: only a successful resolution containing paket.lock can reach the GitHub publisher
    /// decision: updates an open pull request before its branch so the ref update is the final fallible GitHub mutation
    /// invariant: refreshing an open owned pull request performs no GitHub API call after moving its branch
    /// tradeoff: creating a pull request still requires a branch first, so uncertain failures need fail-closed human recovery
    member _.Run(repository: Repository, baseSha: string, result: ResolutionResult) =
        async {
            try
                match result.Status, result.LockFile with
                | NoChange, _ -> return Unchanged
                | Updated, Some lockFile ->
                    let! previousPublication = github.TryGetPublication repository
                    let! currentHead = github.GetBranchHead(repository, Branches.Weekly)

                    let publish = {
                        Repository = repository
                        BaseSha = baseSha
                        Branch = Branches.Weekly
                        Path = PaketFiles.Lock
                        Content = lockFile
                        Title = "chore(deps): update Paket dependencies"
                        Body = PullRequestBody.render result.Changes result.RequirementChanges
                    }

                    let expectedHead = previousPublication |> Option.map _.HeadSha

                    match Branches.planPublication baseSha expectedHead currentHead with
                    | Error message -> return RunFailed [ message ]
                    | Ok publicationPlan ->
                        let parentShas = Branches.commitParents baseSha publicationPlan
                        let! commitSha = github.CreateCommit(publish, parentShas)

                        match publicationPlan, previousPublication with
                        | Branches.FastForwardFrom _, Some previous when previous.IsOpen ->
                            do! github.UpdatePullRequest(publish, previous.PullRequestNumber)
                            do! github.FastForwardBranch(repository, publish.Branch, commitSha)

                            return Published(publication publish.Branch previous.PullRequestNumber commitSha)
                        | Branches.FastForwardFrom _, Some _ ->
                            do! github.FastForwardBranch(repository, publish.Branch, commitSha)
                            let! result = createPullRequestAfterBranchMutation publish commitSha

                            return
                                match result with
                                | Ok value -> Published value
                                | Error message -> RunFailed [ message ]
                        | Branches.CreateFrom _, _ ->
                            do! github.CreateBranch(repository, publish.Branch, commitSha)
                            let! result = createPullRequestAfterBranchMutation publish commitSha

                            return
                                match result with
                                | Ok value -> Published value
                                | Error message -> RunFailed [ message ]
                        | Branches.FastForwardFrom _, None ->
                            return RunFailed [ "a verified branch head requires tracked publication state" ]
                | _ -> return RunFailed result.Messages
            with _ ->
                return RunFailed [ "GitHub publication failed without exposing remote error details." ]
        }
