namespace PaketaBot

type IGitHubGateway =
    abstract GetRepository: owner: string * name: string -> Async<Repository>
    abstract TryGetPublication: Repository -> Async<Publication option>
    abstract Publish: PublishUpdate -> Async<Publication>

type IArtifactStore =
    abstract Create: Repository * sha: string -> Async<string>

type ISandboxRunner =
    abstract Run: RunnerRequest -> Async<RunnerResult>

module PullRequestBody =
    let render changes =
        let rows =
            changes
            |> List.map (fun change -> $"| `{change.Name}` | `{change.Previous}` | `{change.Current}` |")
            |> String.concat "\n"

        $"""{PullRequests.Marker}
PaketaBot updated the versions allowed by `paket.dependencies`.

| Package | From | To |
|---|---:|---:|
{rows}

Generated by PaketaBot. Repository CI remains responsible for validation.
"""

type UpdateService(github: IGitHubGateway, artifacts: IArtifactStore, runner: ISandboxRunner) =
    /// Resolve and publish one repository-local dependency update.
    ///
    /// decision: uses the marked pull request as durable publication state because the Action has no database
    /// invariant: repository archives cross into the runner without PAKETABOT_TOKEN or checkout credentials
    member _.Run(repository: Repository, baseSha: string) =
        async {
            try
                let! artifactPath = artifacts.Create(repository, baseSha)

                let request = {
                    Repository = Repository.fullName repository
                    BaseSha = baseSha
                    ArtifactPath = artifactPath
                }

                let! result = runner.Run request

                match result.Status, result.LockFile with
                | RunnerStatus.NoChange, _ -> return Unchanged
                | RunnerStatus.Updated, Some lockFile ->
                    let! previousPublication = github.TryGetPublication repository

                    let publish = {
                        Repository = repository
                        BaseSha = baseSha
                        PreviousPublication = previousPublication
                        Branch = Branches.Weekly
                        Path = PaketFiles.Lock
                        Content = lockFile
                        Title = "chore(deps): update Paket dependencies"
                        Body = PullRequestBody.render result.Changes
                    }

                    let! publication = github.Publish publish
                    return Published publication
                | _ -> return RunFailed result.Messages
            with ex ->
                return RunFailed [ ex.Message ]
        }
